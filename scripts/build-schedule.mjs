/**
 * Generate the NFL schedule as a SQL data file.
 *
 * Why this runs in Node rather than inside the Worker: ESPN's scoreboard API
 * returns 403 to workerd. Identical headers from Node succeed, and Sleeper works
 * fine from the Worker, so it is ESPN bot-detection on the TLS fingerprint —
 * not something a header can fix.
 *
 * That is arguably the right shape regardless. Kickoff times drive the
 * Thursday-night lock, so they are correctness-critical, and pinning them into a
 * versioned SQL file removes a live third-party dependency from the hot path.
 *
 *   node scripts/build-schedule.mjs            # current season, weeks 1-18
 *   node scripts/build-schedule.mjs 2027       # a specific season
 *
 * Apply with:
 *   npm run schedule:load:local
 *   npm run schedule:load:remote
 *
 * Re-run after flex-scheduling changes; the generated SQL upserts, so it is safe
 * to apply repeatedly.
 */

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT_DIR = path.join(ROOT, 'data')
const ESPN_SCOREBOARD = 'https://site.api.espn.com/apis/site/v2/sports/football/nfl/scoreboard'

/** ESPN abbreviation -> Sleeper abbreviation. Only the ones that differ. */
const TEAM_CODE_MAP = { WSH: 'WAS' }
const normalizeTeam = (code) => {
  const upper = String(code || '').toUpperCase()
  return TEAM_CODE_MAP[upper] || upper
}

function mapStatus(name) {
  switch (name) {
    case 'STATUS_FINAL':
      return 'final'
    case 'STATUS_IN_PROGRESS':
    case 'STATUS_HALFTIME':
    case 'STATUS_END_PERIOD':
      return 'in_progress'
    default:
      return 'scheduled'
  }
}

const sqlString = (value) => (value == null ? 'NULL' : `'${String(value).replace(/'/g, "''")}'`)

async function currentSeason() {
  const res = await fetch('https://api.sleeper.app/v1/state/nfl', { headers: { accept: 'application/json' } })
  if (!res.ok) throw new Error(`Sleeper state ${res.status}`)
  return Number((await res.json()).season)
}

async function fetchWeek(season, week, seasonType = 2) {
  const url = `${ESPN_SCOREBOARD}?dates=${season}&seasontype=${seasonType}&week=${week}`
  const res = await fetch(url, { headers: { accept: 'application/json' } })
  if (!res.ok) throw new Error(`ESPN ${res.status} for week ${week}`)
  return res.json()
}

const season = Number(process.argv[2]) || (await currentSeason())
console.log(`Building schedule for ${season}...`)

const rows = []
const failures = []

for (let week = 1; week <= 18; week += 1) {
  try {
    const data = await fetchWeek(season, week)
    for (const event of data?.events || []) {
      const competition = event.competitions?.[0]
      if (!competition) continue

      const home = competition.competitors?.find((c) => c.homeAway === 'home')
      const away = competition.competitors?.find((c) => c.homeAway === 'away')
      if (!home || !away) continue

      const kickoff = new Date(event.date)
      if (Number.isNaN(kickoff.valueOf())) continue

      rows.push({
        week,
        home: normalizeTeam(home.team?.abbreviation),
        away: normalizeTeam(away.team?.abbreviation),
        kickoff: kickoff.toISOString(),
        status: mapStatus(competition.status?.type?.name || event.status?.type?.name),
      })
    }
    process.stdout.write(`  week ${week}: ${data?.events?.length ?? 0} games\n`)
  } catch (err) {
    failures.push({ week, message: err.message })
    process.stdout.write(`  week ${week}: FAILED — ${err.message}\n`)
  }
}

if (rows.length === 0) {
  console.error('\nNo games retrieved — refusing to write an empty schedule file.')
  process.exit(1)
}

const lines = [
  `-- NFL ${season} regular season schedule.`,
  `-- Generated by scripts/build-schedule.mjs on ${new Date().toISOString()}.`,
  '-- Do not edit by hand; re-run the script after flex-scheduling changes.',
  '-- Upserts, so applying it repeatedly is safe.',
  '',
]

for (const row of rows) {
  lines.push(
    `INSERT INTO nfl_games (season, season_type, week, home_team, away_team, kickoff_at, status, updated_at)`,
    `VALUES (${season}, 'regular', ${row.week}, ${sqlString(row.home)}, ${sqlString(row.away)}, ` +
      `${sqlString(row.kickoff)}, ${sqlString(row.status)}, strftime('%Y-%m-%dT%H:%M:%fZ','now'))`,
    `ON CONFLICT (season, season_type, week, home_team, away_team) DO UPDATE SET`,
    `  kickoff_at = excluded.kickoff_at, status = excluded.status, updated_at = excluded.updated_at;`,
    '',
  )
}

fs.mkdirSync(OUT_DIR, { recursive: true })
const outFile = path.join(OUT_DIR, `schedule-${season}.sql`)
fs.writeFileSync(outFile, lines.join('\n'), 'utf8')

console.log(`\nWrote ${rows.length} games to ${path.relative(ROOT, outFile)}`)
if (failures.length) console.warn(`${failures.length} week(s) failed: ${failures.map((f) => f.week).join(', ')}`)
console.log('\nApply it with:\n  npm run schedule:load:local\n  npm run schedule:load:remote')
